export const LIB = new Map(EXERCISES.map((x) => [x.id, x]));
export const catLabel = (id) => CATEGORIES.find((c) => c.id === id)?.label ?? id;

/** Bibliothekseintrag zu einem Plan-Eintrag (item.lib verweist auf eine andere ID, z. B. Kontrast-Varianten). */
export const libOf = (item) => LIB.get(item.lib ?? item.id) ?? null;

/** Suche über Name, Kategorie, Ausrüstung und Beschreibung (ohne Groß/Klein und Akzente). */
const norm = (s) => String(s ?? '').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '');
export function searchLibrary(q = '', cat = null) {
  const words = norm(q).split(/\s+/).filter(Boolean);
  return EXERCISES.filter((x) => {
    if (cat && x.cat !== cat) return false;
    const hay = norm(`${x.name} ${catLabel(x.cat)} ${x.equip} ${x.desc}`);
    return words.every((w) => hay.includes(w));
  });
}
